// Определение коммерческости запроса по ключевым словам в самом тексте запроса.
//
// Это прямой сигнал (в отличие от utils/pageClassifier.js, который судит о типе
// запроса косвенно — по тому, какие страницы ранжируются в выдаче). Используется
// как приоритетный сигнал в base.js: если в запросе есть явный маркер намерения —
// это надёжнее, чем догадка по URL страниц в топе.

export const COMMERCIAL_QUERY_KEYWORDS = [
  'купить', 'куплю', 'заказать', 'заказ ', 'закажи',
  'цена', 'цены', 'стоимость', 'сколько стоит', 'прайс',
  'скидка', 'скидки', 'акция', 'акции', 'распродажа', 'дешево', 'дешевле', 'недорого',
  'интернет-магазин', 'магазин', 'каталог товаров', 'прокат', 'аренда', 'снять',
  'доставка', 'оптом', 'в розницу', 'под ключ',
];

export const INFORMATIONAL_QUERY_KEYWORDS = [
  'что такое', 'что значит', 'кто такой',
  'как ', 'почему', 'зачем', 'отличие', 'отличия', 'разница между',
  'инструкция', 'руководство', 'гайд', 'пошагово',
  'история', 'определение', 'принцип работы', 'устройство',
  'виды ', 'типы ', 'классификация', 'сравнение',
];

/**
 * Пытается определить тип запроса по ключевым словам в его тексте.
 * @param {string} query
 * @returns {'Коммерческий'|'Информационный'|null} null — явных маркеров нет,
 *   нужно использовать запасной способ (по составу выдачи).
 */
export function detectQueryIntentByKeywords(query) {
  if (!query) return null;

  const lower = ` ${query.toLowerCase()} `;

  const hasCommercial = COMMERCIAL_QUERY_KEYWORDS.some((kw) => lower.includes(kw));
  const hasInfo = INFORMATIONAL_QUERY_KEYWORDS.some((kw) => lower.includes(kw));

  // Оба сигнала сразу ("купить книгу как выбрать") — неоднозначно, отдаём на
  // откуп запасному способу, а не гадаем.
  if (hasCommercial && hasInfo) return null;
  if (hasCommercial) return 'Коммерческий';
  if (hasInfo) return 'Информационный';

  return null;
}
